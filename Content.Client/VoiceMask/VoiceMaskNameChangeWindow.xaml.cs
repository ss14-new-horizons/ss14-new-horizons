namespace Content.Client.VoiceMask;

[GenerateTypedNameReferences]
public sealed partial class VoiceMaskNameChangeWindow : FancyWindow
{
    // NH-Add-Start (Radio job icons)
    [Dependency] private IEntitySystemManager _entitySystem = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    private readonly SpriteSystem _spriteSystem;
    // NH-Add-End

    public Action<string>? OnNameChange;
    public Action<string?>? OnVerbChange;
    public Action? OnToggle;
    public Action? OnAccentToggle;
    public Action<string>? OnVoiceChange; // Corvax-TTS
    public Action<ProtoId<JobIconPrototype>?>? OnJobIconChanged; // NH-Add (Radio job icons)

    private List<(string, string)> _verbs = new();
    private List<TTSVoicePrototype> _voices = new(); // Corvax-TTS

    private string? _verb;
    // NH-Add-Start (Radio job icons)
    private ProtoId<JobIconPrototype>? _currentJobIcon;
    private readonly List<(JobIconGroupPrototype Proto, ContainerButton Button)> _groupButtons = new();
    private string? _selectedGroupId;
    // NH-Add-End
    public VoiceMaskNameChangeWindow()
    {
        RobustXamlLoader.Load(this);
        // NH-Add-Start (Radio job icons)
        IoCManager.InjectDependencies(this);
        _spriteSystem = _entitySystem.GetEntitySystem<SpriteSystem>();

        Tabs.SetTabTitle(0, Loc.GetString("voice-mask-tab-voice"));
        Tabs.SetTabTitle(1, Loc.GetString("voice-mask-tab-job-icon"));

        ClearJobIconButton.OnPressed += _ => OnJobIconChanged?.Invoke(null);
        BuildJobIcons();
        // NH-Add-End

        NameSelectorSet.OnPressed += _ =>
        {
            OnNameChange?.Invoke(NameSelector.Text);
        };

        SpeechVerbSelector.OnItemSelected += args =>
        {
            OnVerbChange?.Invoke((string?) args.Button.GetItemMetadata(args.Id));
            SpeechVerbSelector.SelectId(args.Id);
        };

        ToggleButton.OnPressed += args => OnToggle?.Invoke();
        ToggleAccentButton.OnPressed += args => OnAccentToggle?.Invoke();

        // Corvax-TTS-Start
        if (IoCManager.Resolve<IConfigurationManager>().GetCVar(CCCVars.TTSEnabled))
        {
            TTSContainer.Visible = true;
            ReloadVoices(IoCManager.Resolve<IPrototypeManager>());
        }
        // Corvax-TTS-End
    }

    public void ReloadVerbs(IPrototypeManager proto)
    {
        foreach (var verb in proto.EnumeratePrototypes<SpeechVerbPrototype>())
        {
            _verbs.Add((Loc.GetString(verb.Name), verb.ID));
        }
        _verbs.Sort((a, b) => a.Item1.CompareTo(b.Item1));
    }

    public void AddVerbs()
    {
        SpeechVerbSelector.Clear();

        AddVerb(Loc.GetString("chat-speech-verb-name-none"), null);
        foreach (var (name, id) in _verbs)
        {
            AddVerb(name, id);
        }
    }

    private void AddVerb(string name, string? verb)
    {
        var id = SpeechVerbSelector.ItemCount;
        SpeechVerbSelector.AddItem(name);
        if (verb is {} metadata)
            SpeechVerbSelector.SetItemMetadata(id, metadata);

        if (verb == _verb)
            SpeechVerbSelector.SelectId(id);
    }

    // Corvax-TTS-Start
    private void ReloadVoices(IPrototypeManager proto)
    {
        VoiceSelector.OnItemSelected += args =>
        {
            VoiceSelector.SelectId(args.Id);
            if (VoiceSelector.SelectedMetadata != null)
                OnVoiceChange!((string)VoiceSelector.SelectedMetadata);
        };
        _voices = proto
            .EnumeratePrototypes<TTSVoicePrototype>()
            .Where(o => o.RoundStart)
            .OrderBy(o => Loc.GetString(o.Name))
            .ToList();
        for (var i = 0; i < _voices.Count; i++)
        {
            var name = Loc.GetString(_voices[i].Name);
            VoiceSelector.AddItem(name);
            VoiceSelector.SetItemMetadata(i, _voices[i].ID);
        }
    }
    // Corvax-TTS-End

    // NH-Add-Start (Radio job icons)
    private void BuildJobIcons()
    {
        JobGroupGrid.DisposeAllChildren();
        IconGrid.DisposeAllChildren();
        _groupButtons.Clear();

        var jobGroupButtonGroup = new ButtonGroup();
        var groups = _prototypeManager.EnumeratePrototypes<JobIconGroupPrototype>().ToList();

        foreach (var groupProto in groups)
        {
            if (groupProto.ID == "AdminIconGroup")
                continue;

            var groupButton = CreateGroupButton(groupProto, jobGroupButtonGroup);
            groupButton.OnPressed += _ => SelectGroup(groupProto);

            JobGroupGrid.AddChild(groupButton);
            _groupButtons.Add((groupProto, groupButton));
        }
    }

    private void SelectGroup(JobIconGroupPrototype groupProto)
    {
        _selectedGroupId = groupProto.ID;
        foreach (var (proto, button) in _groupButtons)
        {
            button.Pressed = proto.ID == groupProto.ID;
        }
        SetJobIcons(groupProto.Icons);
    }

    private void SyncSelectedGroup(ProtoId<JobIconPrototype>? currentIcon, bool iconChanged)
    {
        if (_groupButtons.Count == 0)
            return;

        // If icon didn't change and we already have a selection, keep current selection
        if (!iconChanged && _selectedGroupId != null)
            return;

        // If an icon is set, try to find the group containing it
        if (currentIcon != null)
        {
            var match = _groupButtons.FirstOrDefault(g => g.Proto.Icons.Contains(currentIcon.Value));
            if (match.Proto != null)
            {
                SelectGroup(match.Proto);
                return;
            }
        }

        // If nothing was selected yet, select the first group
        if (_selectedGroupId == null && _groupButtons.Count > 0)
        {
            SelectGroup(_groupButtons[0].Proto);
        }
    }

    private void SetJobIcons(IReadOnlyList<ProtoId<JobIconPrototype>> jobIcons)
    {
        IconGrid.DisposeAllChildren();

        foreach (var icon in jobIcons)
        {
            if (!_prototypeManager.TryIndex(icon, out var iconProto))
                continue;

            var texture = _spriteSystem.Frame0(iconProto.Icon);

            var jobIconButton = new TextureButton
            {
                Access = AccessLevel.Public,
                ToolTip = Loc.GetString(iconProto.JobName),
                TextureNormal = texture,
                SetSize = new Vector2(32, 32),
            };

            jobIconButton.OnPressed += _ => OnJobIconChanged?.Invoke(iconProto.ID);

            IconGrid.AddChild(jobIconButton);
        }
    }

    private ContainerButton CreateGroupButton(JobIconGroupPrototype groupProto, ButtonGroup buttonGroup)
    {
        var button = new ContainerButton
        {
            Access = AccessLevel.Public,
            Group = buttonGroup,
            ToggleMode = true,
            StyleClasses = { StyleClass.ButtonOpenBoth },
            Margin = new Thickness(4, 2)
        };

        button.AddChild(new BoxContainer
        {
            SeparationOverride = 6,
            Children =
            {
                new TextureRect
                {
                    Texture = _spriteSystem.Frame0(groupProto.Sprite),
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                    SetSize = new Vector2(24, 24),
                    VerticalAlignment = VAlignment.Center,
                },
                new Label
                {
                    Text = Loc.GetString(groupProto.GroupName),
                    HorizontalExpand = true,
                    VerticalAlignment = VAlignment.Center,
                },
            },
        });

        return button;
    }
    // NH-Add-End

    public void UpdateState(string name, string? verb, bool active, bool accentHide, LocId titleText, string voice, ProtoId<JobIconPrototype>? jobIcon = null) // Corvax-TTS // NH-Edit (Radio job icons: added ProtoId<JobIconPrototype>? jobIcon = null)
    {
        NameSelector.Text = name;
        _verb = verb;
        ToggleButton.Pressed = active;
        ToggleAccentButton.Pressed = accentHide;
        Title = Loc.GetString(titleText);
        for (int id = 0; id < SpeechVerbSelector.ItemCount; id++)
        {
            if (string.Equals(verb, SpeechVerbSelector.GetItemMetadata(id)))
            {
                SpeechVerbSelector.SelectId(id);
                break;
            }
        }

        // Corvax-TTS-Start
        var voiceIdx = _voices.FindIndex(v => v.ID == voice);
        if (voiceIdx != -1)
            VoiceSelector.Select(voiceIdx);
        // Corvax-TTS-End

        // NH-Add-Start (Radio job icons)
        var iconChanged = _currentJobIcon != jobIcon;
        _currentJobIcon = jobIcon;
        if (jobIcon != null && _prototypeManager.TryIndex(jobIcon.Value, out var jobIconProto))
        {
            CurrentJobIcon.Texture = _spriteSystem.Frame0(jobIconProto.Icon);
            CurrentJobIconLabel.Text = Loc.GetString(jobIconProto.JobName);
            CurrentJobIcon.Visible = true;
        }
        else
        {
            CurrentJobIcon.Texture = null;
            CurrentJobIconLabel.Text = Loc.GetString("chat-speech-verb-name-none");
            CurrentJobIcon.Visible = false;
        }

        SyncSelectedGroup(jobIcon, iconChanged);
        // NH-Add-End
    }
}
